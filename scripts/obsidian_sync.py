def synchronize(config: SyncConfig) -> tuple[int, int, list[str]]:
    """Initialize absent notes and atomically update generated result notes."""
    created_curated = _initialize_vault(config)
    bundle = load_artifacts(config)
    output = config.generated_root
    output.mkdir(parents=True, exist_ok=True)
    id_map_path = output / "experiment_id_map.json"
    ids = assign_experiment_ids(bundle.experiments, id_map_path, _all_reserved_ids(config))
    _atomic_write(
        id_map_path,
        json.dumps(ids, indent=2, sort_keys=True, ensure_ascii=True),
    )

    for experiment in bundle.experiments:
        note_path = output / f"{ids[experiment.source_key]}.md"
        _write_generated_note(
            note_path,
            _experiment_markdown(experiment, ids[experiment.source_key]),
        )

    generated_at = datetime.now(UTC).isoformat()
    summary_path = output / "Research Summary.md"
    if config.report_inclusion.get("include_research_summary", True):
        summary_text = _summary_markdown(bundle, generated_at)
    else:
        summary_text = (
            "# Research Summary\n\nSummary details are disabled by `report_inclusion.include_research_summary`."
        )
    _write_generated_note(summary_path, summary_text)
    _write_generated_note(
        output / "Generated Experiment Registry.md",
        _registry_markdown(bundle.experiments, ids),
    )
    _managed_sections(config, bundle, "Research Summary")
    if bundle.issues:
        issue_text = "# Import Issues\n\n"
        issue_text += "These sources could not be fully imported. Resolve the issue and run sync again.\n\n"
        issue_text += "\n".join(f"- {issue}" for issue in bundle.issues)
        _write_generated_note(output / "Import Issues.md", issue_text)
    elif (output / "Import Issues.md").exists():
        _write_generated_note(
            output / "Import Issues.md",
            "# Import Issues\n\nNo source parsing issues were found on the latest sync.",
        )
    return len(created_curated), len(bundle.experiments), bundle.issues


def validate_market_data(path: Path, minimum_score: float = 0.99) -> dict[str, Any]:
    """Validate OHLC integrity without correcting, filtering, or rewriting data."""
    try:
        import pandas as pd
    except ImportError as exc:
        raise RuntimeError("Data validation requires the project's pandas dependency") from exc
    if not path.is_file():
        raise FileNotFoundError(f"Market-data file does not exist: {path}")
    suffix = path.suffix.lower()
    if suffix == ".parquet":
        frame = pd.read_parquet(path)
    elif suffix == ".csv":
        frame = pd.read_csv(path)
    else:
        raise ValueError(f"Unsupported market-data format: {path.suffix}; use CSV or Parquet")
    if frame.empty:
        raise ValueError(f"Market-data file has no rows: {path}")

    timestamp_column = next(
        (name for name in ("timestamp", "time", "datetime", "date") if name in frame.columns),
        None,
    )
    raw_times = frame[timestamp_column] if timestamp_column else frame.index
    parsed_times = pd.DatetimeIndex(pd.to_datetime(raw_times, errors="coerce", utc=True))
    valid_times = [bool(pd.notna(value)) for value in parsed_times]
    invalid_timestamp_count = sum(not valid for valid in valid_times)
    valid_positions = [position for position, valid in enumerate(valid_times) if valid]
    valid_parsed = parsed_times[valid_times]
    timezone_naive = [False] * len(frame)
    if timestamp_column:
        source_values = frame[timestamp_column].tolist()
        for position, value in enumerate(source_values):
            if valid_times[position] and pd.Timestamp(value).tzinfo is None:
                timezone_naive[position] = True
    else:
        index = frame.index
        if not isinstance(index, pd.DatetimeIndex) or index.tz is None:
            timezone_naive = [True] * len(frame)
    naive_count = sum(timezone_naive)
    duplicate_values = valid_parsed.duplicated(keep="first").tolist()
    duplicate_mask = [False] * len(frame)
    for position, duplicate in zip(valid_positions, duplicate_values, strict=True):
        duplicate_mask[position] = bool(duplicate)
    duplicate_count = sum(duplicate_mask)
    unsorted = not valid_parsed.is_monotonic_increasing

    required = ("open", "high", "low", "close")
    missing_columns = [column for column in required if column not in frame.columns]
    if missing_columns:
        raise ValueError(f"Market-data file is missing OHLC columns: {', '.join(missing_columns)}")
    prices = frame.loc[:, list(required)].apply(pd.to_numeric, errors="coerce")
    missing_rows = prices.isna().any(axis=1).tolist()
    finite_rows = np.isfinite(prices.to_numpy(dtype=float)).all(axis=1).tolist()
    nonpositive_rows = (prices <= 0).any(axis=1).tolist()
    invalid_price_rows = [
        bool(nonpositive_rows[position]) or not bool(finite_rows[position]) for position in range(len(frame))
    ]
    invalid_ohlc_rows = (
        (prices["high"] < prices["low"])
        | (prices["open"] < prices["low"])
        | (prices["open"] > prices["high"])
        | (prices["close"] < prices["low"])
        | (prices["close"] > prices["high"])
    ).tolist()
    invalid_rows = [
        bool(missing or invalid_price or invalid_ohlc or not valid_time or is_naive or duplicate)
        for missing, invalid_price, invalid_ohlc, valid_time, is_naive, duplicate in zip(
            missing_rows,
            invalid_price_rows,
            invalid_ohlc_rows,
            valid_times,
            timezone_naive,
            duplicate_mask,
            strict=True,
        )
    ]
    invalid_row_count = sum(invalid_rows)
    quality_score = max(0.0, 1.0 - invalid_row_count / len(frame))
    time_differences = valid_parsed.to_series().diff().dropna()
    cadence = time_differences.median() if not time_differences.empty else pd.Timedelta(0)
    gap_count = int((time_differences > cadence * 1.5).sum()) if cadence > pd.Timedelta(0) else 0
    largest_gap = str(time_differences.max()) if not time_differences.empty else "Not Available"
    passed = (
        invalid_timestamp_count == 0
        and duplicate_count == 0
        and not unsorted
        and naive_count == 0
        and not any(missing_rows)
        and not any(invalid_price_rows)
        and not any(invalid_ohlc_rows)
        and quality_score >= minimum_score
    )
    return {
        "path": str(path.resolve()),
        "rows": len(frame),
        "timestamp_column": timestamp_column or "index",
        "invalid_timestamp_count": invalid_timestamp_count,
        "timezone_naive_timestamp_count": naive_count,
        "duplicate_timestamp_count": duplicate_count,
        "timestamps_sorted": not unsorted,
        "missing_ohlc_row_count": sum(missing_rows),
        "nonfinite_or_nonpositive_price_row_count": sum(invalid_price_rows),
        "invalid_ohlc_row_count": sum(invalid_ohlc_rows),
        "largest_positive_time_gap": largest_gap,
        "candidate_gap_count": gap_count,
        "data_quality_score": quality_score,
        "minimum_score": minimum_score,
        "passed": passed,
        "note": "Gap counts are descriptive only; market closures and session gaps are not automatically errors.",
    }


def _format_inspect(config: SyncConfig) -> str:
    lines = [
        f"Project root: {config.project_root}",
        f"Vault path: {config.vault_path}",
        f"Generated notes directory: {config.generated_notes_dir}",
        f"Vault exists: {config.vault_path.is_dir()}",
        f"Minimum data-quality score: {config.minimum_data_quality_score:.4f}",
        "Result files:",
    ]
    for path in config.result_paths:
        lines.append(f"  {'OK' if path.is_file() else 'MISSING'} {path}")
    lines.append("Registry files:")
    for path in config.registry_paths:
        lines.append(f"  {'OK' if path.is_file() else 'MISSING'} {path}")
    lines.append("Metadata files:")
    for path in config.metadata_paths:
        lines.append(f"  {'OK' if path.is_file() else 'MISSING'} {path}")
    lines.append("Configured data files:")
    for path in config.data_paths:
        lines.append(f"  {'OK' if path.is_file() else 'MISSING'} {path}")
    return "\n".join(lines)


def _list_records(config: SyncConfig) -> str:
    bundle = load_artifacts(config)
    ids = assign_experiment_ids(
        bundle.experiments,
        config.generated_root / "experiment_id_map.json",
        _all_reserved_ids(config),
    )
    lines = ["ID        STATUS                     STRATEGY"]
    for item in bundle.experiments:
        lines.append(f"{ids[item.source_key]:<9} {item.status:<26} {item.strategy}")
    if not bundle.experiments:
        lines.append("No experiment records were imported.")
    if bundle.issues:
        lines.extend(["", "Import issues:"] + [f"- {issue}" for issue in bundle.issues])
    return "\n".join(lines)


def _run_validation(paths: list[Path], score: float) -> tuple[list[dict[str, Any]], list[str]]:
    results: list[dict[str, Any]] = []
    errors: list[str] = []
    for path in paths:
        try:
            results.append(validate_market_data(path, score))
        except (OSError, RuntimeError, ValueError) as exc:
            errors.append(f"{path}: {exc}")
    return results, errors


