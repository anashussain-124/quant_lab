        f"instrument/timeframe: {_clean_cell(summary.get('instrument'))}/"
        f"{_clean_cell(summary.get('timeframe'))}",
        f"- Holdout accessed: {_clean_cell(summary.get('holdout_accessed'))}",
        f"- PBO: {pbo}",
        f"- Code version recorded by source: `{_clean_cell(summary.get('code_version'))}`",
