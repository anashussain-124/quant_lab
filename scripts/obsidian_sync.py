def _clean_cell(value: Any) -> str:
    if value is None:
        return "Not Available"
    if isinstance(value, (dict, list, tuple)):
        text = json.dumps(value, sort_keys=True, ensure_ascii=True, default=str)
    elif isinstance(value, float) and not math.isfinite(value):
        text = "Infinity" if value > 0 else ("-Infinity" if value < 0 else "Not Available")
    else:
        text = str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def _metrics_markdown(metrics: dict[str, Any]) -> str:
    if not metrics:
        return "_No metrics were present in the source artifact._"
    lines = ["| Metric | Measured value |", "|---|---|"]
    for key, value in metrics.items():
        lines.append(f"| {_clean_cell(key)} | {_clean_cell(value)} |")
    return "\n".join(lines)


