@dataclass(frozen=True)
class SyncConfig:
    project_root: Path
    vault_path: Path
    generated_notes_dir: str
    result_paths: tuple[Path, ...]
    registry_paths: tuple[Path, ...]
    metadata_paths: tuple[Path, ...]
    data_paths: tuple[Path, ...]
    report_inclusion: dict[str, bool]
    minimum_data_quality_score: float

    @property
    def generated_root(self) -> Path:
        relative = Path(self.generated_notes_dir)
        if relative.is_absolute() or ".." in relative.parts:
            raise ValueError("generated_notes_dir must be a safe path inside the vault")
        root = (self.vault_path / relative).resolve()
        if not root.is_relative_to(self.vault_path.resolve()):
            raise ValueError("generated_notes_dir resolves outside the vault")
        return root


@dataclass
class Experiment:
    source_key: str
    title: str
    legacy_source_key: str | None = None
    strategy: str = "Unknown"
    strategy_version: str = "Unknown"
    created_at: str = "Unknown"
    code_version: str = "Unknown"
    dataset_id: str = "Unknown"
    date_range: str = "Unknown"
    instrument: str = "Unknown"
    timeframe: str = "Unknown"
    parameters: dict[str, Any] = field(default_factory=dict)
    command: str = "Not Available"
    engine_version: str = "Unknown"
    assumptions: dict[str, Any] = field(default_factory=dict)
    result_path: str = "Unknown"
    artifact_hash: str = "Unknown"
    status: str = "Needs Review"
    environment: str = "BACKTEST"
    data_environment: str = "Unknown"
    metrics: dict[str, Any] = field(default_factory=dict)
    interpretation: str = "Not recorded in the source artifact."
    next_action: str = "Review the source artifact and record a human decision."


@dataclass
class ArtifactBundle:
    experiments: list[Experiment] = field(default_factory=list)
    campaign_summaries: list[dict[str, Any]] = field(default_factory=list)
    cost_rows: list[dict[str, str]] = field(default_factory=list)
    issues: list[str] = field(default_factory=list)


def _resolve_path(root: Path, value: str, label: str) -> Path:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{label} must be a non-empty path string")
    path = Path(value).expanduser()
    return path.resolve() if path.is_absolute() else (root / path).resolve()


def load_config(config_path: Path) -> SyncConfig:
    """Read and validate the JSON configuration without touching the vault."""
    path = config_path.expanduser().resolve()
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise ValueError(f"Cannot read configuration {path}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(f"Malformed JSON configuration {path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise ValueError("Configuration root must be a JSON object")

    project_root = _resolve_path(path.parent.parent, raw.get("project_root", "."), "project_root")
    if not project_root.is_dir():
        raise ValueError(f"Project root does not exist: {project_root}")
    vault_value = raw.get("vault_path")
    if not isinstance(vault_value, str) or not vault_value.strip():
        raise ValueError("Set vault_path to the existing Obsidian vault path")
    vault_path = _resolve_path(project_root, vault_value, "vault_path")
    if not vault_path.is_dir():
        raise ValueError(f"Obsidian vault does not exist: {vault_path}")

    generated_notes_dir = raw.get("generated_notes_dir", GENERATED_FOLDER)
    if not isinstance(generated_notes_dir, str) or not generated_notes_dir.strip():
        raise ValueError("generated_notes_dir must be a non-empty relative path")
    if Path(generated_notes_dir).is_absolute() or ".." in Path(generated_notes_dir).parts:
        raise ValueError("generated_notes_dir must be a safe relative path inside the vault")

    def read_paths(key: str) -> tuple[Path, ...]:
        values = raw.get(key, [])
        if not isinstance(values, list):
            raise ValueError(f"{key} must be a list of paths")
        return tuple(_resolve_path(project_root, item, f"{key} entry") for item in values)

    report_inclusion = raw.get(
        "report_inclusion",
        {"include_trial_notes": True, "include_research_summary": True},
    )
    if not isinstance(report_inclusion, dict) or any(
        not isinstance(value, bool) for value in report_inclusion.values()
    ):
        raise ValueError("report_inclusion must be an object of boolean settings")
    minimum_score = raw.get("minimum_data_quality_score", 0.99)
    if (
        not isinstance(minimum_score, (int, float))
        or isinstance(minimum_score, bool)
        or not 0.0 <= float(minimum_score) <= 1.0
    ):
        raise ValueError("minimum_data_quality_score must be between 0 and 1")

    config = SyncConfig(
        project_root=project_root,
        vault_path=vault_path,
        generated_notes_dir=generated_notes_dir,
        result_paths=read_paths("result_paths"),
        registry_paths=read_paths("registry_paths"),
        metadata_paths=read_paths("metadata_paths"),
        data_paths=read_paths("data_paths"),
        report_inclusion={str(key): value for key, value in report_inclusion.items()},
        minimum_data_quality_score=float(minimum_score),
    )
    _ = config.generated_root
    return config


def _relative_path(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return str(path.resolve())


def _version_from_path(path: Path) -> str:
    for part in path.parts:
        if re.fullmatch(r"v\d+", part, re.IGNORECASE):
            return part.lower()
    match = re.search(r"(?:reports_)?(v\d+)", str(path), re.IGNORECASE)
    return match.group(1).lower() if match else "Unknown"


def _dataset_details(data: dict[str, Any], report_path: Path) -> tuple[str, str, str, str]:
    dataset_path = str(data.get("path", ""))
    dataset_name = Path(dataset_path).name.lower()
    instrument = "XAUUSD" if "xauusd" in dataset_name else "Unknown"
    timeframe_match = re.search(r"_(m\d+|h\d+|d\d+)_", dataset_name, re.IGNORECASE)
    timeframe = timeframe_match.group(1).upper() if timeframe_match else "Unknown"
    start = data.get("start", "Unknown")
    end = data.get("end", "Unknown")
    date_range = f"{start} to {end}" if start != "Unknown" and end != "Unknown" else "Unknown"
    dataset_id = str(data.get("sha256") or data.get("data_hash") or "Unknown")
    if dataset_id == "Unknown":
        match = re.search(r"_([0-9a-f]{8,64})\.csv$", report_path.name, re.IGNORECASE)
        if match:
            dataset_id = f"filename-hash-prefix:{match.group(1)}"
    return dataset_id, date_range, instrument, timeframe


def _file_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _status_from_verdict(verdict: Any) -> str:
    normalized = str(verdict or "").strip().upper().replace("-", "_")
    if normalized in {"FAIL", "REJECTED", "NO_EDGE_FOUND", "FAILED"}:
        return "Rejected" if normalized != "FAILED" else "Failed"
    if normalized in {"PASS", "PASS_CANDIDATE", "CANDIDATE_FOR_VALIDATION"}:
        return "Candidate for Validation"
    if normalized in {"VALIDATED"}:
        return "Validated"
    if normalized in {"COMPLETED", "COMPLETE"}:
        return "Completed"
    return "Needs Review"


def _parse_json_report(path: Path, root: Path, include_trials: bool) -> tuple[list[Experiment], dict[str, Any]]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError("JSON report root must be an object")
    version = _version_from_path(path)
    data = raw.get("data", {})
    data = data if isinstance(data, dict) else {}
    dataset_id, date_range, instrument, timeframe = _dataset_details(data, path)
    created_at = str(raw.get("generated_utc", "Unknown"))
    code_version = str(raw.get("code_commit", "Unknown"))
    cost_model = raw.get("cost_model", {})
    protocol = raw.get("protocol", {})
    assumptions = cost_model if isinstance(cost_model, dict) else {}
    source = _relative_path(path, root)
    source_hash = _file_hash(path)
    trials = raw.get("trials", [])
    experiments: list[Experiment] = []

    if include_trials and isinstance(trials, list):
        for index, trial in enumerate(trials, start=1):
            if not isinstance(trial, dict):
                continue
            config_id = str(trial.get("config_id") or f"trial-{index:03d}")
            trial_identity = {
                "created_at": created_at,
                "code_version": code_version,
                "dataset_id": dataset_id,
                "cost_model": assumptions,
                "trial": trial,
            }
            trial_hash = hashlib.sha256(
                json.dumps(trial_identity, sort_keys=True, separators=(",", ":"), default=str).encode("utf-8")
            ).hexdigest()
            oos = trial.get("oos", {})
            oos = oos if isinstance(oos, dict) else {}
            gates = trial.get("gates", {})
            gates = gates if isinstance(gates, dict) else {}
            verdict = "FAIL" if any(value is False for value in gates.values()) else "Needs Review"
            metrics = {f"oos.{key}": value for key, value in oos.items()}
            if trial.get("dsr") is not None:
                metrics["dsr"] = trial["dsr"]
            metrics["gate_results"] = gates
            experiments.append(
                Experiment(
                    source_key=f"{source}#{config_id}@{trial_hash[:16]}",
                    title=f"{config_id} — {trial.get('family', 'strategy trial')}",
                    legacy_source_key=f"{source}#{config_id}",
                    strategy=str(trial.get("family", "Unknown")),
                    strategy_version=version,
                    created_at=created_at,
                    code_version=code_version,
                    dataset_id=dataset_id,
                    date_range=date_range,
                    instrument=instrument,
                    timeframe=timeframe,
                    parameters=trial.get("params", {}) if isinstance(trial.get("params"), dict) else {},
                    engine_version=str(assumptions.get("version", "Unknown")),
                    assumptions=assumptions,
                    result_path=f"{source} (trial {config_id})",
                    artifact_hash=source_hash,
                    status=_status_from_verdict(verdict),
                    environment="BACKTEST",
                    data_environment=str(raw.get("environment", "Unknown")),
                    metrics=metrics,
                    interpretation="This is one configuration in a registered search; it is not a validated strategy.",
                    next_action="Retain the recorded gate outcome; do not retune this frozen trial.",
                )
            )

    summary = {
        "source": source,
        "version": version,
        "generated_utc": created_at,
        "verdict": raw.get("verdict", "Unknown"),
        "holdout_accessed": raw.get("holdout_accessed", "Unknown"),
        "trial_count": protocol.get("trials", len(trials)) if isinstance(protocol, dict) else len(trials),
        "dataset_id": dataset_id,
        "date_range": date_range,
        "instrument": instrument,
        "timeframe": timeframe,
        "data_rows": data.get("rows", "Unknown"),
        "data_source": data.get("source", "Unknown"),
        "code_version": code_version,
        "cost_model": assumptions,
        "pbo": raw.get("pbo", {}).get("pbo", "Unknown") if isinstance(raw.get("pbo"), dict) else "Unknown",
        "gate_failure_counts": raw.get("gate_failure_counts", {}),
        "trials": trials,
    }
    return experiments, summary


def _parse_registry(path: Path, root: Path) -> tuple[list[Experiment], list[str]]:
    experiments: list[Experiment] = []
    issues: list[str] = []
    source = _relative_path(path, root)
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
            if not isinstance(record, dict):
                raise ValueError("record must be a JSON object")
        except (json.JSONDecodeError, ValueError) as exc:
            issues.append(f"{source}:{line_number}: {exc}")
            continue
        record_hash = hashlib.sha256(line.encode("utf-8")).hexdigest()
        results = record.get("results", {})
        results = results if isinstance(results, dict) else {}
        strategy = record.get("strategy") or results.get("strategy") or "Unknown"
        params = record.get("params", {})
        params = params if isinstance(params, dict) else {}
        data_hash = record.get("data_hash") or results.get("data_hash") or "Unknown"
        verdict = record.get("verdict") or results.get("verdict")
        metrics = dict(results)
        if record.get("pbo") is not None:
            metrics["pbo"] = record["pbo"]
        experiments.append(
            Experiment(
                source_key=f"{source}#{line_number}@{hashlib.sha256(line.encode('utf-8')).hexdigest()[:16]}",
                title=f"{strategy} — registry record {line_number:04d}",
                legacy_source_key=f"{source}#{line_number}",
                strategy=str(strategy),
                strategy_version=_version_from_path(path),
                created_at=str(record.get("timestamp_utc", "Unknown")),
                code_version=str(
                    record.get("code_commit") or record.get("code_hash") or results.get("code_version") or "Unknown"
                ),
                dataset_id=str(data_hash),
                parameters=params,
                engine_version=str(results.get("code_version", "Unknown")),
                result_path=f"{source} (line {line_number})",
                artifact_hash=record_hash,
                status=_status_from_verdict(verdict),
                environment=str(record.get("environment", "BACKTEST")),
                data_environment=("HISTORICAL_REAL" if re.fullmatch(r"[0-9a-fA-F]{64}", str(data_hash)) else "Unknown"),
                metrics=metrics,
                interpretation=str(record.get("note", "Imported from the append-only experiment registry.")),
                next_action="Keep the trial in the registry; review linked reports before proposing any new test.",
            )
        )
    return experiments, issues


def _parse_metadata(path: Path, root: Path) -> tuple[list[Experiment], list[str]]:
    """Load manually maintained, append-only experiment metadata JSONL."""
    experiments: list[Experiment] = []
    issues: list[str] = []
    source = _relative_path(path, root)
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
            if not isinstance(record, dict):
                raise ValueError("record must be a JSON object")
            status = record.get("status")
            if not isinstance(status, str) or status not in EXPERIMENT_STATUSES:
                raise ValueError(f"status must be one of {', '.join(sorted(EXPERIMENT_STATUSES))}")
            parameters = record.get("parameters", {})
            assumptions = record.get("cost_assumptions", {})
            metrics = record.get("metrics", {})
            for key, value in (
                ("parameters", parameters),
                ("cost_assumptions", assumptions),
                ("metrics", metrics),
            ):
                if not isinstance(value, dict):
                    raise ValueError(f"{key} must be a JSON object")
            environment = record.get("environment", "BACKTEST")
            data_environment = record.get("data_environment", "Unknown")
            if not isinstance(environment, str) or environment not in ENVIRONMENTS:
                raise ValueError(f"environment must be one of {', '.join(sorted(ENVIRONMENTS))}")
            if not isinstance(data_environment, str) or data_environment not in ENVIRONMENTS | {"Unknown"}:
                raise ValueError(f"data_environment must be one of {', '.join(sorted(ENVIRONMENTS | {'Unknown'}))}")
            experiment = Experiment(
                source_key=f"{source}#{line_number}",
                title=_text(record.get("title") or record.get("strategy"), "Untitled experiment"),
                strategy=_text(record.get("strategy"), "Unknown"),
                strategy_version=_text(record.get("strategy_version"), "Unknown"),
                created_at=_text(record.get("created_at_utc"), "Unknown"),
                code_version=_text(record.get("git_commit"), "Unknown"),
                dataset_id=_text(record.get("dataset_id"), "Unknown"),
                date_range=_text(record.get("date_range"), "Unknown"),
                instrument=_text(record.get("instrument"), "Unknown"),
                timeframe=_text(record.get("timeframe"), "Unknown"),
                parameters=parameters,
                command=_text(record.get("backtest_command"), "Not Available"),
                engine_version=_text(record.get("engine_version"), "Unknown"),
                assumptions=assumptions,
                result_path=_text(record.get("result_path"), "Not Available"),
                artifact_hash="Unknown",
                status=status,
                environment=environment,
                data_environment=data_environment,
                metrics=metrics,
                interpretation=_text(record.get("interpretation"), "Not recorded."),
                next_action=_text(record.get("next_action"), "Review the experiment record."),
            )
            experiments.append(experiment)
        except (json.JSONDecodeError, ValueError) as exc:
            issues.append(f"{source}:{line_number}: {exc}")
    return experiments, issues


def _text(value: Any, default: str) -> str:
    return default if value is None or (isinstance(value, str) and not value.strip()) else str(value)


def _parse_cost_csv(path: Path, root: Path) -> tuple[list[Experiment], list[dict[str, str]]]:
    experiments: list[Experiment] = []
    rows: list[dict[str, str]] = []
    source = _relative_path(path, root)
    source_hash = _file_hash(path)
    with path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if not reader.fieldnames:
            raise ValueError("CSV has no header")
        required = {"hypothesis", "parameter_set"}
        if not required.issubset(reader.fieldnames):
            raise ValueError(f"CSV must include columns: {', '.join(sorted(required))}")
        for line_number, row in enumerate(reader, start=2):
            if row is None:
                continue
            row_values = {str(key): str(value or "") for key, value in row.items() if key is not None}
            rows.append(row_values)
            if not row_values.get("hypothesis", "").strip() or not row_values.get("parameter_set", "").strip():
                raise ValueError(f"missing hypothesis or parameter_set at CSV line {line_number}")
            try:
                parameters = json.loads(row_values.get("params", "{}") or "{}")
            except json.JSONDecodeError as exc:
                raise ValueError(f"invalid params JSON at CSV line {line_number}: {exc}") from exc
            if not isinstance(parameters, dict):
                raise ValueError(f"params at CSV line {line_number} must be a JSON object")
            hypothesis = row_values["hypothesis"]
            parameter_set = row_values["parameter_set"]
            row_hash = hashlib.sha256(
                json.dumps(row_values, sort_keys=True, separators=(",", ":")).encode("utf-8")
            ).hexdigest()
            metrics: dict[str, Any] = {}
            for key, value in row_values.items():
                if key in {"hypothesis", "parameter_set", "params"}:
                    continue
                metrics[key] = _parse_scalar(value)
            experiments.append(
                Experiment(
                    source_key=f"{source}#{hypothesis}:{parameter_set}@{row_hash[:16]}",
                    title=f"{hypothesis} — {parameter_set}",
                    legacy_source_key=f"{source}#{hypothesis}:{parameter_set}",
                    strategy=hypothesis,
                    strategy_version=_version_from_path(path),
                    dataset_id=_dataset_id_from_csv_name(path.name),
                    parameters=parameters,
                    engine_version="Not Available in source CSV",
                    result_path=f"{source} (line {line_number})",
                    artifact_hash=source_hash,
                    status="Completed",
                    environment="BACKTEST",
                    data_environment="HISTORICAL_REAL",
                    metrics=metrics,
                    interpretation=(
                        "Measured cost decomposition; the source CSV does not provide a promotion decision."
                    ),
                    next_action=(
                        "Use the negative/positive gross result only as evidence for this template and cost model."
                    ),
                )
            )
    return experiments, rows


def _dataset_id_from_csv_name(name: str) -> str:
    match = re.search(r"_([0-9a-f]{8,64})\.csv$", name, re.IGNORECASE)
    return f"filename-hash-prefix:{match.group(1)}" if match else "Unknown"


def _parse_scalar(value: str) -> Any:
    if not value.strip():
        return "Not Available"
    lowered = value.strip().lower()
    if lowered in {"true", "false"}:
        return lowered == "true"
    try:
        number = float(value)
    except ValueError:
        return value
    if math.isnan(number):
        return "Not Available"
    if math.isinf(number):
        return "Infinity" if number > 0 else "-Infinity"
    if number.is_integer():
        return int(number)
    return number


def load_artifacts(config: SyncConfig) -> ArtifactBundle:
    """Parse every configured result/registry, retaining malformed-source errors."""
    bundle = ArtifactBundle()
    include_trials = config.report_inclusion.get("include_trial_notes", True)
    for path in config.registry_paths:
        if not path.is_file():
            bundle.issues.append(f"Configured registry is missing: {_relative_path(path, config.project_root)}")
            continue
        try:
            records, issues = _parse_registry(path, config.project_root)
            bundle.experiments.extend(records)
            bundle.issues.extend(issues)
        except (OSError, UnicodeError) as exc:
            bundle.issues.append(f"{_relative_path(path, config.project_root)}: {exc}")
    for path in config.metadata_paths:
        if not path.is_file():
            bundle.issues.append(f"Configured metadata file is missing: {_relative_path(path, config.project_root)}")
            continue
        try:
            records, issues = _parse_metadata(path, config.project_root)
            bundle.experiments.extend(records)
            bundle.issues.extend(issues)
        except (OSError, UnicodeError) as exc:
            bundle.issues.append(f"{_relative_path(path, config.project_root)}: {exc}")
    for path in config.result_paths:
        if not path.is_file():
            bundle.issues.append(f"Configured result file is missing: {_relative_path(path, config.project_root)}")
            continue
        try:
            if path.suffix.lower() == ".json":
                experiments, summary = _parse_json_report(path, config.project_root, include_trials)
                bundle.experiments.extend(experiments)
                bundle.campaign_summaries.append(summary)
            elif path.suffix.lower() == ".csv":
                experiments, rows = _parse_cost_csv(path, config.project_root)
                bundle.experiments.extend(experiments)
                bundle.cost_rows.extend(rows)
            else:
                bundle.issues.append(
                    f"{_relative_path(path, config.project_root)}: unsupported result format {path.suffix or '(none)'}"
                )
        except (OSError, UnicodeError, json.JSONDecodeError, csv.Error, ValueError) as exc:
            bundle.issues.append(f"{_relative_path(path, config.project_root)}: {exc}")
    return bundle


def _all_reserved_ids(config: SyncConfig) -> set[int]:
    reserved: set[int] = set()
    roots = [config.vault_path, config.project_root / "docs", config.project_root / "experiments"]
    skipped = {".git", ".venv", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"}
    for root in roots:
        if not root.exists():
            continue
        paths = root.rglob("*") if root.is_dir() else [root]
        for path in paths:
            if not path.is_file() or path.suffix.lower() not in {".md", ".json", ".jsonl", ".txt"}:
                continue
            try:
                if any(part in skipped for part in path.parts):
                    continue
                content = path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            reserved.update(int(match) for match in ID_PATTERN.findall(content))
    return reserved


def assign_experiment_ids(experiments: list[Experiment], id_map_path: Path, reserved_ids: set[int]) -> dict[str, str]:
    try:
        stored = json.loads(id_map_path.read_text(encoding="utf-8")) if id_map_path.exists() else {}
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"Cannot read experiment ID map {id_map_path}: {exc}") from exc
    if not isinstance(stored, dict) or any(
        not isinstance(key, str) or not isinstance(value, str) or not ID_PATTERN.fullmatch(value)
        for key, value in stored.items()
    ):
        raise ValueError(f"Experiment ID map has invalid content: {id_map_path}")
    mapping = dict(stored)
    used = set(reserved_ids)
    for value in mapping.values():
        match = ID_PATTERN.fullmatch(value)
        if match is None:
            raise ValueError(f"Experiment ID map has an invalid ID: {value}")
        used.add(int(match.group(1)))
    next_id = max(used, default=0) + 1
    for experiment in experiments:
        if experiment.source_key in mapping:
            continue
        if experiment.legacy_source_key in mapping:
            mapping[experiment.source_key] = mapping.pop(experiment.legacy_source_key)
            continue
        while next_id in used:
            next_id += 1
        mapping[experiment.source_key] = f"EXP-{next_id:03d}"
        used.add(next_id)
        next_id += 1
    return mapping


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".tmp",
            delete=False,
        ) as stream:
            temp_name = stream.name
            stream.write(content.rstrip() + "\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp_name, path)
    except OSError as exc:
        if temp_name:
            with suppress(OSError):
                Path(temp_name).unlink(missing_ok=True)
        raise OSError(f"Atomic write failed for {path}: {exc}") from exc


def _write_generated_note(path: Path, content: str) -> None:
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if GENERATED_NOTE_MARKER not in existing:
            raise ValueError(f"Refusing to overwrite an unmarked note in the generated directory: {path}")
    _atomic_write(path, f"{GENERATED_NOTE_MARKER}\n\n{content}")


def _update_managed_section(existing: str, body: str) -> str:
    block = f"{BEGIN_MARKER}\n{body.strip()}\n{END_MARKER}"
    begin = existing.find(BEGIN_MARKER)
    end = existing.find(END_MARKER)
    if (begin == -1) != (end == -1) or (begin != -1 and end < begin):
        raise ValueError("Existing note has an incomplete generated-section marker pair")
    if begin != -1:
        end += len(END_MARKER)
        return f"{existing[:begin].rstrip()}\n\n{block}\n{existing[end:].lstrip()}"
    return f"{existing.rstrip()}\n\n{block}\n" if existing.strip() else f"{block}\n"


def _managed_note(vault: Path, title: str) -> Path | None:
    matches = [p for p in vault.rglob("*.md") if p.stem.casefold() == title.casefold()]
    matches = [p for p in matches if GENERATED_FOLDER not in p.as_posix()]
    return sorted(matches, key=lambda p: (len(p.parts), str(p).casefold()))[0] if matches else None


def _initialize_vault(config: SyncConfig) -> list[Path]:
    for folder in FOLDERS:
        (config.vault_path / folder).mkdir(parents=True, exist_ok=True)
    created: list[Path] = []
    notes = _curated_notes()
    for relative_path, content in notes.items():
        target = config.vault_path / relative_path
        if _managed_note(config.vault_path, target.stem):
            continue
        if target.exists():
            continue
        _atomic_write(target, content)
        created.append(target)
    return created


