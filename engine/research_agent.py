"""Phase 11: Research Agent — L0 Read/Report, L1 Propose, L2 Sandbox.

Per AGENTS.md A3:
- L0: Read data, write reports (default)
- L1: Propose experiments; human approves
- L2: Run approved experiment templates in a sandbox
- L3: Modify risk/execution code — FORBIDDEN

The agent can:
- Analyze data quality and market conditions
- Propose experiments (parameter grids, strategy variants)
- Run sandboxed experiments (backtests, simulations)
- Generate reports with findings
- Never modify risk config, risk code, or safety gates
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any


class AgentLevel(str, Enum):
    """Research agent autonomy levels."""
    L0 = "L0"  # Read data, write reports
    L1 = "L1"  # Propose experiments; human approves
    L2 = "L2"  # Run approved templates in sandbox
    L3 = "L3"  # Modify risk/execution — FORBIDDEN


@dataclass
class ExperimentProposal:
    """Proposed experiment."""
    name: str
    description: str
    hypothesis: str
    parameters: dict[str, Any]
    success_criteria: str
    estimated_duration_minutes: float = 60.0
    approved: bool = False
    approved_by: str = ""
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    def approve(self, approver: str) -> None:
        """Approve the experiment."""
        self.approved = True
        self.approved_by = approver


@dataclass
class ExperimentResult:
    """Result of a sandboxed experiment."""
    proposal: ExperimentProposal
    status: str  # "RUNNING", "COMPLETED", "FAILED"
    results: dict[str, Any] = field(default_factory=dict)
    start_time: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    end_time: datetime | None = None

    def complete(self, results: dict[str, Any]) -> None:
        """Mark as completed."""
        self.status = "COMPLETED"
        self.results = results
        self.end_time = datetime.now(timezone.utc)

    def fail(self, error: str) -> None:
        """Mark as failed."""
        self.status = "FAILED"
        self.results = {"error": error}
        self.end_time = datetime.now(timezone.utc)


@dataclass
class ResearchReport:
    """Research report generated by the agent."""
    title: str
    summary: str
    findings: list[str] = field(default_factory=list)
    recommendations: list[str] = field(default_factory=list)
    data_quality: float = 0.0
    market_regime: str = "UNKNOWN"
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))

    def to_markdown(self) -> str:
        """Convert to markdown."""
        lines = [
            f"# {self.title}",
            "",
            f"**Date:** {self.timestamp.strftime('%Y-%m-%d %H:%M UTC')}",
            f"**Market Regime:** {self.market_regime}",
            f"**Data Quality:** {self.data_quality:.2f}",
            "",
            "## Summary",
            "",
            self.summary,
            "",
            "## Findings",
            "",
        ]
        for finding in self.findings:
            lines.append(f"- {finding}")
        lines.extend(["", "## Recommendations", ""])
        for rec in self.recommendations:
            lines.append(f"- {rec}")
        return "\n".join(lines)


class ResearchAgent:
    """Research agent with autonomy levels."""

    def __init__(
        self,
        level: AgentLevel = AgentLevel.L0,
        name: str = "research_agent",
    ) -> None:
        self.level = level
        self.name = name
        self._proposals: list[ExperimentProposal] = []
        self._experiments: list[ExperimentResult] = []
        self._reports: list[ResearchReport] = []
        self._iterations = 0

    @property
    def autonomy_level(self) -> str:
        """Get autonomy level description."""
        descriptions = {
            AgentLevel.L0: "Read data, write reports",
            AgentLevel.L1: "Propose experiments; human approves",
            AgentLevel.L2: "Run approved templates in sandbox",
        }
        return descriptions.get(self.level, "Unknown")

    def generate_report(
        self,
        title: str,
        data_quality: float = 0.0,
        market_regime: str = "UNKNOWN",
        findings: list[str] | None = None,
        recommendations: list[str] | None = None,
    ) -> ResearchReport:
        """Generate a research report."""
        report = ResearchReport(
            title=title,
            summary=f"Analysis completed at autonomy level {self.level.value}",
            findings=findings or [],
            recommendations=recommendations or [],
            data_quality=data_quality,
            market_regime=market_regime,
        )
        self._reports.append(report)
        return report

    def propose_experiment(
        self,
        name: str,
        description: str,
        hypothesis: str,
        parameters: dict[str, Any],
        success_criteria: str,
        estimated_duration_minutes: float = 60.0,
    ) -> ExperimentProposal | None:
        """Propose an experiment (L1+)."""
        if self.level == AgentLevel.L0:
            return None  # Cannot propose at L0

        proposal = ExperimentProposal(
            name=name,
            description=description,
            hypothesis=hypothesis,
            parameters=parameters,
            success_criteria=success_criteria,
            estimated_duration_minutes=estimated_duration_minutes,
        )
        self._proposals.append(proposal)
        return proposal

    def run_experiment(
        self,
        proposal: ExperimentProposal,
        experiment_fn: callable | None = None,
    ) -> ExperimentResult | None:
        """Run an approved experiment in sandbox (L2)."""
        if self.level != AgentLevel.L2:
            return None  # Can only run at L2

        if not proposal.approved:
            return None  # Must be approved

        result = ExperimentResult(proposal=proposal, status="RUNNING")
        self._experiments.append(result)

        try:
            if experiment_fn:
                experiment_results = experiment_fn(proposal.parameters)
                result.complete(experiment_results)
            else:
                result.complete({"status": "sandbox_placeholder"})
        except Exception as e:
            result.fail(str(e))

        return result

    def analyze_market_conditions(
        self,
        price_data: dict[str, Any],
        quality_score: float = 0.0,
    ) -> dict[str, Any]:
        """Analyze market conditions."""
        self._iterations += 1
        return {
            "regime": price_data.get("regime", "UNKNOWN"),
            "volatility": price_data.get("volatility", 0.0),
            "quality_score": quality_score,
            "iteration": self._iterations,
        }

    def get_proposals(self) -> list[ExperimentProposal]:
        """Get all proposals."""
        return list(self._proposals)

    def get_experiments(self) -> list[ExperimentResult]:
        """Get all experiments."""
        return list(self._experiments)

    def get_reports(self) -> list[ResearchReport]:
        """Get all reports."""
        return list(self._reports)

    def get_summary(self) -> dict[str, Any]:
        """Get agent summary."""
        return {
            "name": self.name,
            "level": self.level.value,
            "autonomy": self.autonomy_level,
            "iterations": self._iterations,
            "proposals": len(self._proposals),
            "experiments": len(self._experiments),
            "reports": len(self._reports),
        }


class ExperimentTemplate:
    """Sandbox experiment template."""

    def __init__(self, name: str, description: str, parameter_schema: dict[str, Any]) -> None:
        self.name = name
        self.description = description
        self.parameter_schema = parameter_schema

    def validate_parameters(self, parameters: dict[str, Any]) -> tuple[bool, str]:
        """Validate parameters against schema."""
        for key, value in self.parameter_schema.items():
            if key not in parameters:
                return False, f"Missing parameter: {key}"
            expected_type = value.get("type")
            if expected_type and not isinstance(parameters[key], eval(expected_type)):
                return False, f"Parameter {key} has wrong type"
        return True, "OK"


