def test_experiment_ids_are_stable_and_never_reuse_reserved_ids(tmp_path: Path) -> None:
    item = Experiment(source_key="registry.jsonl#1", title="trial")
    id_map = tmp_path / "generated" / "id-map.json"
    first = assign_experiment_ids([item], id_map, {1, 2, 7})
    assert first[item.source_key] == "EXP-008"
    id_map.parent.mkdir()
    id_map.write_text(json.dumps(first), encoding="utf-8")

    second = assign_experiment_ids(
        [item, Experiment(source_key="registry.jsonl#2", title="second")],
        id_map,
        {1, 2, 7, 8},
    )
    assert second[item.source_key] == "EXP-008"
    assert second["registry.jsonl#2"] == "EXP-009"


def test_experiment_id_migration_preserves_ids_but_changed_source_gets_new_id(tmp_path: Path) -> None:
    id_map = tmp_path / "generated" / "id-map.json"
    id_map.parent.mkdir()
    id_map.write_text(json.dumps({"report.json#dc01": "EXP-010"}), encoding="utf-8")
    migrated = Experiment(
        source_key="report.json#dc01@newhash",
        legacy_source_key="report.json#dc01",
        title="dc01",
    )
    mapping = assign_experiment_ids([migrated], id_map, {10})
    assert mapping == {"report.json#dc01@newhash": "EXP-010"}

    changed = Experiment(source_key="report.json#dc01@differenthash", title="dc01")
    updated = assign_experiment_ids([changed], id_map, {10})
    assert updated[changed.source_key] == "EXP-011"


def test_managed_section_preserves_manual_text_and_replaces_generated_text() -> None:
    note = "# My note\n\nManual paragraph."
    first = _update_managed_section(note, "Generated one.")
    second = _update_managed_section(first, "Generated two.")
    assert "Manual paragraph." in second
    assert "Generated one." not in second
    assert second.count("BEGIN QUANT LAB GENERATED SECTION") == 1
    assert "Generated two." in second
    with pytest.raises(ValueError, match="incomplete"):
        _update_managed_section("text <!-- BEGIN QUANT LAB GENERATED SECTION -->", "content")


