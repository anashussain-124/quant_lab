def test_sync_is_idempotent_and_preserves_existing_notes(tmp_path: Path) -> None:
    config_path = _config_file(tmp_path)
    config = load_config(config_path)
    (config.vault_path / "Quant Research Dashboard.md").write_text("# Dashboard\n\nManual status.\n", encoding="utf-8")
    (config.vault_path / "Experiment Registry.md").write_text("# Registry\n\nHandwritten plan.\n", encoding="utf-8")
    (config.vault_path / "Data Quality Checklist.md").write_text("# Quality\n\nManual checklist.\n", encoding="utf-8")

    registry_path = config.project_root / "experiments" / "registry.jsonl"
    registry_path.parent.mkdir()
    registry_path.write_text(
        json.dumps({
            "timestamp_utc": "2026-10-22T00:00:00+00:00",
            "strategy": "fixture",
            "data_hash": "data-hash",
            "results": {"n": 2, "verdict": "PASS"},
        })
        + "\n",
        encoding="utf-8",
    )
    config_path_data = json.loads(config_path.read_text(encoding="utf-8"))
    config_path_data["registry_paths"] = ["experiments/registry.jsonl"]
    config_path.write_text(json.dumps(config_path_data), encoding="utf-8")
    config = load_config(config_path)

    curated_count1, imported_count1, issues1 = synchronize(config)
    generated_registry = config.generated_root / "Generated Experiment Registry.md"
    first_content = generated_registry.read_text(encoding="utf-8")
    curated_count2, imported_count2, issues2 = synchronize(config)
    second_content = generated_registry.read_text(encoding="utf-8")

    assert curated_count1 >= 1
    assert curated_count2 == 0
    assert imported_count1 == imported_count2 == 1
    assert not issues1 and not issues2
    assert first_content == second_content
    assert "Handwritten plan." in (config.vault_path / "Experiment Registry.md").read_text(encoding="utf-8")
    assert "Manual status." in (config.vault_path / "Quant Research Dashboard.md").read_text(encoding="utf-8")
    assert "Manual checklist." in (config.vault_path / "Data Quality Checklist.md").read_text(encoding="utf-8")
    assert len(list(config.generated_root.glob("EXP-*.md"))) == 1


def test_market_data_validation_checks_ohlc_timezone_and_gaps(tmp_path: Path) -> None:
    good = tmp_path / "good.csv"
    good.write_text(
        "timestamp,open,high,low,close\n2026-01-01T00:00:00+00:00,10,12,9,11\n2026-01-01T01:00:00+00:00,11,13,10,12\n",
        encoding="utf-8",
    )
    report = validate_market_data(good)
    assert report["passed"] is True
    assert report["data_quality_score"] == 1.0
    assert report["candidate_gap_count"] == 0

    bad = tmp_path / "bad.csv"
    bad.write_text(
        "timestamp,open,high,low,close\n2026-01-01T00:00:00,10,8,9,11\n2026-01-01T00:00:00,11,13,10,12\n",
        encoding="utf-8",
    )
    bad_report = validate_market_data(bad)
    assert bad_report["passed"] is False
    assert bad_report["timezone_naive_timestamp_count"] == 2
    assert bad_report["duplicate_timestamp_count"] == 1
    assert bad_report["invalid_ohlc_row_count"] >= 1


def test_market_data_validation_rejects_empty_and_unsupported_files(tmp_path: Path) -> None:
    empty = tmp_path / "empty.csv"
    empty.write_text("timestamp,open,high,low,close\n", encoding="utf-8")
    with pytest.raises(ValueError, match="no rows"):
        validate_market_data(empty)
    unsupported = tmp_path / "bars.txt"
    unsupported.write_text("x", encoding="utf-8")
    with pytest.raises(ValueError, match="Unsupported"):
        validate_market_data(unsupported)
