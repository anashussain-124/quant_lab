def _config_file(tmp_path: Path, *, result_paths: list[str] | None = None) -> Path:
    project = tmp_path / "project"
    vault = tmp_path / "vault"
    project.mkdir()
    vault.mkdir()
    config_dir = project / "configs"
    config_dir.mkdir()
    config = {
        "project_root": "..",
        "vault_path": str(vault),
        "generated_notes_dir": "07 Results & Reports/Generated by Quant Lab",
        "result_paths": result_paths or [],
        "registry_paths": [],
        "data_paths": [],
        "report_inclusion": {
            "include_trial_notes": True,
            "include_research_summary": True,
        },
        "minimum_data_quality_score": 0.99,
    }
    config_path = config_dir / "obsidian_sync.json"
    config_path.write_text(json.dumps(config), encoding="utf-8")
    return config_path


